/**
 * Writes `_headers` and `_redirects` for the web export.
 *
 * Both files are read by Cloudflare Pages and by Netlify, which is why they
 * were chosen over a host-specific config: the same build deploys to either.
 *
 * THE CSP IS THE POINT OF THIS FILE. Web has no Keystore, so the session sits
 * in localStorage where any injected script could read it. The policy below
 * allows no inline script except the exact bootstrap Expo emits, matched by
 * hash — computed from the export that was just built, so an Expo upgrade
 * moves the hash instead of quietly breaking the app.
 *
 * `style-src` does allow `unsafe-inline`, and that is not laziness:
 * react-native-web builds its stylesheet at runtime and injects it. There is no
 * way to hash it and no build-time alternative. Inline STYLE is a far smaller
 * hazard than inline script — it cannot read localStorage — but it is a real
 * relaxation and worth naming rather than hiding.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const out = process.argv[2];
if (!out) throw new Error('usage: write-web-headers.mjs <export-dir>');

const apiOrigin = process.env.API_ORIGIN;
if (!apiOrigin) throw new Error('API_ORIGIN must be set, or connect-src will block every request');

/** Every file under a directory, recursively. */
function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(out);
const html = files.filter((file) => file.endsWith('.html'));

// ------------------------------------------------------- inline scripts --

const hashes = new Set();
for (const file of html) {
  const source = readFileSync(file, 'utf8');
  for (const match of source.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    const body = match[1];
    // An empty inline block needs no hash and would produce a useless one.
    if (body.trim() === '') continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

/*
 * More than a couple of distinct inline scripts means the assumption behind
 * this file has changed — probably an Expo upgrade emitting per-page code.
 * Failing loudly is right: the alternative is a policy with a dozen hashes
 * nobody reviews, or a silent fallback to `unsafe-inline`.
 */
if (hashes.size > 3) {
  throw new Error(
    `Found ${hashes.size} distinct inline scripts; expected at most 3. ` +
      'Check what the export is emitting before relaxing the CSP.',
  );
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')}`.trim(),
  // See the note at the top: react-native-web injects its stylesheet.
  "style-src 'self' 'unsafe-inline'",
  // jsDelivr serves the exercise demonstration images (BRD §6.8).
  "img-src 'self' data: blob: https://cdn.jsdelivr.net",
  "font-src 'self' data:",
  "media-src 'self' data: blob:",
  `connect-src 'self' ${apiOrigin}`,
  "worker-src 'self' blob:",
  "manifest-src 'self'",
  // Nothing here embeds, frames, or posts a form anywhere.
  "object-src 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
  "form-action 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/write-web-headers.mjs — do not edit by hand.
# Regenerated on every \`pnpm build:web\`, so the CSP hash always matches the
# bundle it ships with.

/*
  Content-Security-Policy: ${csp}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  Permissions-Policy: geolocation=(), microphone=(), payment=(), usb=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

# Hashed bundles are immutable, so they can be cached forever.
/_expo/static/*
  Cache-Control: public, max-age=31536000, immutable

/assets/*
  Cache-Control: public, max-age=31536000, immutable

# HTML must not be cached, or a deploy does not reach anyone who has visited.
/*.html
  Cache-Control: no-cache
`;

writeFileSync(join(out, '_headers'), headers);

// ----------------------------------------------------------- redirects --

/*
 * Expo static-exports one HTML file per route, so `/insights` already resolves
 * without help. DYNAMIC routes do not: `athlete/[id].html` exists on disk but
 * `/athlete/abc-123` matches no file and 404s. Each one needs a rewrite to its
 * bracket file, which the client then reads the real id out of the URL.
 *
 * Discovered from the export rather than listed by hand, so a new dynamic
 * route cannot ship without its rewrite.
 */
const dynamic = html
  .map((file) => relative(out, file).split(sep).join('/'))
  .filter((route) => route.includes('['))
  .map((route) => {
    const pattern = route.replace(/\.html$/, '').replace(/\[([^\]]+)\]/g, ':$1');
    return `/${pattern}  /${route}  200`;
  });

const redirects = `# Generated by scripts/write-web-headers.mjs — do not edit by hand.
#
# Static routes need nothing: Expo exports one HTML file each. These are the
# dynamic ones, where the path carries an id that no file on disk matches.
# 200 rather than 301: the URL has to stay as the user typed it, because the
# client reads the id out of it.

${dynamic.join('\n')}

# Anything else genuinely missing gets the app's own not-found screen.
/*  /+not-found.html  404
`;

writeFileSync(join(out, '_redirects'), redirects);

console.log(`    CSP script-src hashes : ${hashes.size}`);
console.log(`    connect-src           : ${apiOrigin}`);
console.log(`    dynamic route rewrites: ${dynamic.length}`);
for (const rule of dynamic) console.log(`      ${rule}`);
